from datetime import datetime
from math import isfinite
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator


class SoilReadingCreate(BaseModel):
    field_id: int = Field(gt=0)

    nitrogen: float | None = Field(
        default=None,
        ge=0
    )

    phosphorus: float | None = Field(
        default=None,
        ge=0
    )

    potassium: float | None = Field(
        default=None,
        ge=0
    )

    ph: float | None = Field(
        default=None,
        ge=0,
        le=14
    )

    moisture: float | None = Field(
        default=None,
        ge=0,
        le=100
    )

    organic_carbon: float | None = Field(
        default=None,
        ge=0
    )

    @field_validator(
        "nitrogen",
        "phosphorus",
        "potassium",
        "ph",
        "moisture",
        "organic_carbon",
    )
    @classmethod
    def validate_finite(cls, value: float | None) -> float | None:
        if value is not None and not isfinite(value):
            raise ValueError("measurement must be finite")
        return value

    @model_validator(mode="before")
    @classmethod
    def reject_client_timestamp(cls, values: Any) -> Any:
        if isinstance(values, dict) and "recorded_at" in values:
            raise ValueError("recorded_at is generated by the database")
        return values

    @model_validator(mode="after")
    def require_measurement(self) -> "SoilReadingCreate":
        measurements = (
            self.nitrogen,
            self.phosphorus,
            self.potassium,
            self.ph,
            self.moisture,
            self.organic_carbon,
        )
        if all(value is None for value in measurements):
            raise ValueError("at least one soil measurement is required")
        return self


class SoilReadingResponse(BaseModel):
    id: int
    field_id: int
    nitrogen: float | None
    phosphorus: float | None
    potassium: float | None
    ph: float | None
    moisture: float | None
    organic_carbon: float | None
    recorded_at: datetime

    model_config = ConfigDict(
        from_attributes=True
    )