import pytest
from pydantic import ValidationError

from app.schemas.soil import SoilReadingCreate


def test_valid_full_soil_reading():
    reading = SoilReadingCreate(
        field_id=1,
        nitrogen=40,
        phosphorus=20,
        potassium=30,
        ph=6.5,
        moisture=25,
        organic_carbon=1.2,
    )

    assert reading.field_id == 1
    assert reading.moisture == 25


def test_valid_partial_soil_reading():
    reading = SoilReadingCreate(field_id=1, moisture=25)

    assert reading.moisture == 25
    assert reading.nitrogen is None


def test_all_null_measurements_are_rejected():
    with pytest.raises(ValidationError, match="at least one soil measurement"):
        SoilReadingCreate(field_id=1)


@pytest.mark.parametrize(
    "field_name",
    ["nitrogen", "phosphorus", "potassium", "organic_carbon"],
)
def test_negative_nutrients_are_rejected(field_name):
    with pytest.raises(ValidationError):
        SoilReadingCreate(field_id=1, **{field_name: -0.1})


@pytest.mark.parametrize("ph", [-0.1, 14.1])
def test_invalid_ph_is_rejected(ph):
    with pytest.raises(ValidationError):
        SoilReadingCreate(field_id=1, ph=ph)


@pytest.mark.parametrize("moisture", [-0.1, 100.1])
def test_invalid_moisture_is_rejected(moisture):
    with pytest.raises(ValidationError):
        SoilReadingCreate(field_id=1, moisture=moisture)


@pytest.mark.parametrize(
    "field_name",
    [
        "nitrogen",
        "phosphorus",
        "potassium",
        "ph",
        "moisture",
        "organic_carbon",
    ],
)
@pytest.mark.parametrize("value", [float("inf"), float("-inf"), float("nan")])
def test_non_finite_measurements_are_rejected(field_name, value):
    with pytest.raises(ValidationError):
        SoilReadingCreate(field_id=1, **{field_name: value})


@pytest.mark.parametrize("field_id", [0, -1])
def test_invalid_field_ids_are_rejected(field_id):
    with pytest.raises(ValidationError):
        SoilReadingCreate(field_id=field_id, moisture=25)


def test_client_recorded_at_is_rejected():
    with pytest.raises(ValidationError, match="generated by the database"):
        SoilReadingCreate(
            field_id=1,
            moisture=25,
            recorded_at="2026-10-20T00:00:00",
        )
